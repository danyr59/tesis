import json
import re
import ast
from sentence_transformers import SentenceTransformer
import chromadb
import torch

# Configuración
JSONL_PATH = "time_series_generation.jsonl"
CHROMA_DB_PATH = "./memoria_maestro"
COLLECTION_NAME = "time_series_generation"



# Compilar regex una sola vez (más rápido)
PATTERN_LISTA = re.compile(
    r'\[\s*(?:-?\d+(?:\.\d+)?|\'[\dA-Za-z.-]+\'|"[\dA-Za-z.-]+")'
    r'(?:\s*,\s*(?:-?\d+(?:\.\d+)?|\'[\dA-Za-z.-]+\'|"[\dA-Za-z.-]+"))*\s*\]'
)

if torch.cuda.is_available():
    device = "cuda"
elif torch.backends.mps.is_available():
    device = "mps"
else:
    device = "cpu"
print(f"Modelo cargado usando: {device}")

# Modelo (cambia a uno más rápido si quieres)
model = SentenceTransformer('all-mpnet-base-v2', device=device)
# O el original: model = SentenceTransformer('all-mpnet-base-v2')

# Cliente Chroma
client = chromadb.PersistentClient(path=CHROMA_DB_PATH)
try:
    client.delete_collection(COLLECTION_NAME)
except:
    pass
collection = client.create_collection(name=COLLECTION_NAME)

# --- Funciones auxiliares optimizadas ---

import torch
import psutil

def get_dynamic_embed_batch(device='cpu', default=32):
    """
    Devuelve un tamaño de lote recomendado para generar embeddings,
    basado en el dispositivo y la memoria disponible.

    Args:
        device (str): 'cuda', 'mps' o 'cpu'
        default (int): valor por defecto si no se puede determinar

    Returns:
        int: tamaño de lote sugerido
    """
    if device == 'cuda' and torch.cuda.is_available():
        try:
            free_mem, total_mem = torch.cuda.mem_get_info()
            free_gb = free_mem / (1024**3)
            # Heurística según VRAM libre (ajusta los umbrales a tu gusto)
            if free_gb > 10:
                return 64
            elif free_gb > 6:
                return 48
            elif free_gb > 4:
                return 32
            else:
                return 16
        except:
            return default

    elif device == 'mps':
        # En Apple Silicon (MPS) no hay una API directa para memoria GPU,
        # pero la memoria es unificada. Podemos usar la RAM total como referencia.
        try:
            ram_gb = psutil.virtual_memory().total / (1024**3)
            if ram_gb > 32:
                return 64
            elif ram_gb > 16:
                return 32
            else:
                return 16
        except:
            return default

    else:  # CPU
        try:
            ram_gb = psutil.virtual_memory().total / (1024**3)
            if ram_gb > 32:
                return 32   # En CPU, lotes muy grandes pueden saturar la RAM
            elif ram_gb > 16:
                return 16
            else:
                return 8
        except:
            return default

def get_dynamic_chroma_batch():
    ram_gb = psutil.virtual_memory().total / (1024**3)
    if ram_gb > 32: return 200
    elif ram_gb > 16: return 100
    else: return 50

def extract_all_time_series(text):
    """Extrae todas las listas usando ast.literal_eval (más rápido y robusto)."""
    series = []
    for match in PATTERN_LISTA.finditer(text):
        try:
            # literal_eval convierte directamente a lista de Python
            lst = ast.literal_eval(match.group())
            # Asegurar que es lista (por si acaso)
            if isinstance(lst, list):
                series.append(lst)
        except (SyntaxError, ValueError):
            # Fallback al método antiguo (casi nunca ocurrirá)
            pass
    return series

def clean_description(text):
    """Elimina las listas y espacios extra de forma más eficiente."""
    # Un solo re.sub con patrón compilado
    return re.sub(r'\s+', ' ', PATTERN_LISTA.sub('', text)).strip()

def build_search_text(entry):
    domain = entry['metadata']['original_domain']
    task = entry['metadata']['task_type']
    question = clean_description(entry['input'])
    response = entry['output']
    return f"Dominio: {domain}. Tarea: {task}. Pregunta: {question}. Respuesta: {response}."



ids_batch = []
embeddings_batch = []
metadatas_batch = []
documents_batch = []

def flush_batch():
    """Inserta el lote acumulado en Chroma y limpia las listas."""
    if ids_batch:
        collection.add(
            ids=ids_batch,
            embeddings=embeddings_batch,
            metadatas=metadatas_batch,
            documents=documents_batch
        )
        ids_batch.clear()
        embeddings_batch.clear()
        metadatas_batch.clear()
        documents_batch.clear()

EMBEDDING_BATCH_SIZE = get_dynamic_embed_batch(device)
BATCH_SIZE = get_dynamic_chroma_batch()
print(f"Tamaño de lote para Chroma: {BATCH_SIZE}")
print(f"Tamaño de lote para embeddings: {EMBEDDING_BATCH_SIZE}")

# --- Procesamiento por lotes ---
# Leer y procesar en lotes de embeddings
with open(JSONL_PATH, 'r', encoding='utf-8') as f:
    lines_buffer = []   # Para acumular textos de búsqueda y metadatos
    entries_buffer = [] # Para guardar los datos de cada entrada

    for line in f:
        entry = json.loads(line)

        # 1. Extraer series (con ast.literal_eval)
        series_input = extract_all_time_series(entry['input'])
        series_output = extract_all_time_series(entry['output'])
        series_data = {
            "input": [{"longitud_puntos": len(x), "serie": x} for x in series_input],
            "output": [{"longitud_puntos": len(x), "serie": x} for x in series_output]
        }
        series_json = json.dumps(series_data, separators=(',', ':'))

        # 2. Construir texto para embedding
        search_text = build_search_text(entry)

        # Guardar temporalmente para el lote de embeddings
        lines_buffer.append(search_text)
        entries_buffer.append({
            "id": entry['id'],
            "metadata": {
                "id": entry['id'],
                "domain": entry['metadata']['original_domain'],
                "task_type": entry['metadata']['task_type'],
                "question": entry['input'],
                "response": entry['output'],
                "time_series": series_json
                # search_text no se guarda en metadata (ya está en documents)
            }
        })
               # Cuando el buffer alcanza el tamaño de lote, procesamos los embeddings
        if len(lines_buffer) >= EMBEDDING_BATCH_SIZE:
            embeddings = model.encode(lines_buffer, batch_size=EMBEDDING_BATCH_SIZE, show_progress_bar=False)

            for i, emb in enumerate(embeddings):
                ids_batch.append(entries_buffer[i]["id"])
                embeddings_batch.append(emb.tolist())
                metadatas_batch.append(entries_buffer[i]["metadata"])
                documents_batch.append(lines_buffer[i])

            # Si el lote de Chroma también está lleno, lo insertamos
            if len(ids_batch) >= BATCH_SIZE:
                flush_batch()

            # Limpiar buffers temporales
            lines_buffer.clear()
            entries_buffer.clear()

    # Procesar el último lote (si queda algo)
    if lines_buffer:
        embeddings = model.encode(lines_buffer, batch_size=EMBEDDING_BATCH_SIZE, show_progress_bar=True)
        for i, emb in enumerate(embeddings):
            ids_batch.append(entries_buffer[i]["id"])
            embeddings_batch.append(emb.tolist())
            metadatas_batch.append(entries_buffer[i]["metadata"])
            documents_batch.append(lines_buffer[i])

        # Insertar resto
        flush_batch()

# Si quedaron registros en el buffer de Chroma (por si no se llegó a BATCH_SIZE)
flush_batch()

print(f"Índice construido con {collection.count()} documentos en {CHROMA_DB_PATH}")

